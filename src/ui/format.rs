/// Format an integer with thin-space (U+2009) thousands grouping: 12 345 678
pub fn format_token_count(n: i64) -> String {
    let negative = n < 0;
    let abs = n.unsigned_abs();
    let digits = abs.to_string();
    let mut result = String::with_capacity(digits.len() + digits.len() / 3);
    for (i, ch) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            result.push('\u{2009}');
        }
        result.push(ch);
    }
    if negative {
        format!("-{}", result)
    } else {
        result
    }
}

/// Build the token details line: "12 345 input · 678 output [· 456 reasoning]"
pub fn format_token_details(usage: &TokenUsage) -> String {
    let mut parts = vec![
        format!("{} input", format_token_count(usage.input_tokens)),
        format!("{} output", format_token_count(usage.output_tokens)),
    ];
    if let Some(reasoning) = usage.reasoning_tokens {
        parts.push(format!("{} reasoning", format_token_count(reasoning)));
    }
    parts.join(" \u{00b7} ")
}

/// Build the cache line: "9 012 read [· 234 write]", or None if no cache data.
pub fn format_token_cache(usage: &TokenUsage) -> Option<String> {
    let mut parts = Vec::new();
    if let Some(read) = usage.cache_read_tokens {
        parts.push(format!("{} read", format_token_count(read)));
    }
    if let Some(write) = usage.cache_write_tokens {
        parts.push(format!("{} write", format_token_count(write)));
    }
    if parts.is_empty() {
        None
    } else {
        Some(parts.join(" \u{00b7} "))
    }
}

/// Build analytics primary summary: "12 345 input / 678 output / 13 023 total".
pub fn format_analytics_token_primary(input_tokens: i64, output_tokens: i64) -> String {
    let total = input_tokens + output_tokens;
    format!(
        "{} input / {} output / {} total",
        format_token_count(input_tokens),
        format_token_count(output_tokens),
        format_token_count(total)
    )
}

/// Build analytics secondary summary for optional cache/reasoning data.
pub fn format_analytics_token_secondary(
    cache_read_tokens: Option<i64>,
    cache_write_tokens: Option<i64>,
    reasoning_tokens: Option<i64>,
) -> Option<String> {
    let mut parts = Vec::new();

    let mut cache_parts = Vec::new();
    if let Some(read) = cache_read_tokens {
        cache_parts.push(format!("{} read", format_token_count(read)));
    }
    if let Some(write) = cache_write_tokens {
        cache_parts.push(format!("{} write", format_token_count(write)));
    }
    if !cache_parts.is_empty() {
        parts.push(format!("cache: {}", cache_parts.join(" \u{00b7} ")));
    }

    if let Some(reasoning) = reasoning_tokens {
        parts.push(format!("reasoning: {}", format_token_count(reasoning)));
    }

    if parts.is_empty() {
        None
    } else {
        Some(parts.join(" \u{00b7} "))
    }
}

/// Explanatory tooltip for the token details line.
pub fn token_details_tooltip(usage: &TokenUsage) -> String {
    let mut lines = vec![
        "Input: tokens sent to the model (prompt + context)".to_string(),
        "Output: tokens generated by the model".to_string(),
    ];
    if usage.reasoning_tokens.is_some() {
        lines.push("Reasoning: extra reasoning tokens when the assistant reports them".to_string());
    }
    lines.join("\n")
}

/// Explanatory tooltip for the cache line.
pub fn token_cache_tooltip() -> &'static str {
    "Read: tokens served from prompt cache\n\
     Write: tokens stored in prompt cache for future requests\n\
     Depending on provider, cache tokens may overlap with input tokens"
}

/// Concise token semantics help text for analytics and detail views.
pub fn token_semantics_help_tooltip() -> &'static str {
    "Input: tokens sent to the model\n\
     Output: tokens generated by the model\n\
     Reasoning: extra reasoning tokens when the assistant reports them\n\
     Cache: cache activity; depending on provider, cache tokens may overlap with input tokens"
}

/// Format a session duration in seconds as a compact human-readable string.
///
/// - `< 60s` → `"< 1m"`
/// - `< 1h`  → `"Nm"`
/// - `≥ 1h`  → `"Nh Mm"` (minutes omitted when 0)
pub fn format_session_duration(seconds: i64) -> String {
    if seconds < 60 {
        "< 1m".to_string()
    } else if seconds < 3600 {
        format!("{}m", seconds / 60)
    } else {
        let hours = seconds / 3600;
        let minutes = (seconds % 3600) / 60;
        if minutes == 0 {
            format!("{}h", hours)
        } else {
            format!("{}h {}m", hours, minutes)
        }
    }
}

/// Return the dominant activity string using the design precedence:
/// edits > commands > reads > messages.
pub fn format_dominant_activity(
    edit_count: usize,
    command_count: usize,
    read_count: usize,
    message_count: usize,
) -> String {
    if edit_count > 0 {
        pluralize(edit_count, "edit", "edits")
    } else if command_count > 0 {
        pluralize(command_count, "command", "commands")
    } else if read_count > 0 {
        pluralize(read_count, "read", "reads")
    } else {
        pluralize(message_count, "message", "messages")
    }
}

fn pluralize(count: usize, singular: &str, plural: &str) -> String {
    if count == 1 {
        format!("1 {singular}")
    } else {
        format!("{count} {plural}")
    }
}

/// Map a stored ending_status to its UI display label.
/// Returns `None` for `"clean"` and `"unknown"` (hidden in the UI).
pub fn ending_label(status: &str) -> Option<&'static str> {
    match status {
        "abrupt" => Some("interrupted"),
        "error" => Some("failed"),
        _ => None,
    }
}

/// CSS class for a session ending label.
pub fn ending_css_class(status: &str) -> &'static str {
    match status {
        "clean" => "ending-completed",
        "abrupt" => "ending-interrupted",
        "error" => "ending-failed",
        _ => "ending-unknown",
    }
}

